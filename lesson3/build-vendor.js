// Writes vendor/inline.js: the preview libraries as strings. Only used when
// index.html is opened straight from disk (file://), where Chrome won't let the
// sandboxed preview frames load vendor/*.js themselves.
// Run from this folder after changing anything in vendor/: node build-vendor.js
const fs = require('fs');
const path = require('path');

const names = ['react.development.js', 'react-dom.development.js', 'router.umd.min.js',
  'react-router.production.min.js', 'react-router-dom.production.min.js'];
const sources = {};
names.forEach(name => {
  sources[name] = fs.readFileSync(path.join(__dirname, 'vendor', name), 'utf8').replace(/<\/script/gi, '<\\/script');
});
fs.writeFileSync(path.join(__dirname, 'vendor', 'inline.js'),
  '// Generated by build-vendor.js. Do not edit.\nwindow.LiveVendor = ' + JSON.stringify(sources) + ';\n');
console.log('Wrote vendor/inline.js');
